export const bySlug = (slug?: string) => SKILLS.find((s) => s.slug === slug)

/** Українська множина для слова «оголошення»: 1/2–4 → оголошення, 0/5+/11–14 → оголошень */
export function adsPlural(n: number): string {
    const d10 = n % 10
    const d100 = n % 100
    const many = d10 === 0 || d10 >= 5 || (d100 >= 11 && d100 <= 14)
    return many ? "оголошень" : "оголошення"
}
